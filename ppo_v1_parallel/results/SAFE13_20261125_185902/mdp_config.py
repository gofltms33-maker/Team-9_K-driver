#     · SUMO 가 대신 멈춰 주지 않는다 (보조 규칙 금지). 빨간불에 정지선을 넘으면
#       REWARD 의 red_light_penalty 를 받고 에피소드가 끝난다.
#
#   내비게이션 (지도 수준 경로 안내 — "300 m 앞 좌회전" 정도, 차로 정보는 없음)
